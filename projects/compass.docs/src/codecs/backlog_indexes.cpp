struct capture {
    std::string id;
    std::string title;
    std::string description;
    std::string filetags;
};

std::string ascii_lower(std::string_view text) {
    std::string out(text);
    std::ranges::transform(out, out.begin(), [](unsigned char c) {
        return static_cast<char>(std::tolower(c));
    });
    return out;
}

/**
 * @brief The value after the first colon of @p line, stripped.
 */
std::string after_colon(std::string_view line) {
    return std::string(co::strip(line.substr(line.find(':') + 1)));
}

/**
 * @brief The frontmatter of a capture, each field from its first line
 * with a value; the script stops reading once every field has a line.
 */
capture read_frontmatter(std::string_view text) {
    capture c;
    std::array<bool, 4> seen{};
    for (const auto line : co::split_lines(text)) {
        const auto stripped = co::strip(line);
        const auto folded = ascii_lower(stripped);
        if (c.id.empty() && stripped.starts_with(":ID:")) {
            c.id = co::strip(stripped.substr(4));
            seen[0] = true;
        } else if (c.title.empty() && folded.starts_with("#+title:")) {
            c.title = after_colon(stripped);
            seen[1] = true;
        } else if (c.description.empty() &&
            folded.starts_with("#+description:")) {
            c.description = after_colon(stripped);
            seen[2] = true;
        } else if (c.filetags.empty() && folded.starts_with("#+filetags:")) {
            c.filetags = after_colon(stripped);
            seen[3] = true;
        }
        if (std::ranges::all_of(seen, [](bool b) { return b; }))
            break;
    }
    return c;
}

std::vector<capture> gather(const ct::corpus_view& v,
    std::string_view bucket) {
    const auto dir = std::string(backlog_root) + std::string(bucket) + "/";
    std::vector<std::string_view> paths;
    for (const auto path : v.list_files(dir, ".org")) {
        const auto rest = path.substr(dir.size());
        const auto slash = rest.find('/');
        if (slash == std::string_view::npos ||
            rest.substr(slash) == "/story.org")
            paths.push_back(path);
    }
    std::ranges::stable_sort(paths, co::component_less);
    std::vector<capture> out;
    for (const auto path : paths) {
        auto c = read_frontmatter(v.read_file(path).value_or(""));
        if (!c.id.empty() && !c.title.empty())
            out.push_back(std::move(c));
    }
    std::ranges::stable_sort(out, {}, [](const capture& c) {
        return ascii_lower(c.title);
    });
    return out;
}

std::string display_tags(std::string_view filetags) {
    auto raw = co::strip(filetags);
    while (raw.starts_with(':'))
        raw.remove_prefix(1);
    while (raw.ends_with(':'))
        raw.remove_suffix(1);
    constexpr std::array<std::string_view, 5> boilerplate{"capture", "inbox",
        "next", "deferred", "discarded"};
    std::string out;
    std::size_t from = 0;
    while (from <= raw.size()) {
        auto to = raw.find(':', from);
        if (to == std::string_view::npos)
            to = raw.size();
        const auto tag = raw.substr(from, to - from);
        if (!tag.empty() && std::ranges::find(boilerplate, tag) ==
                boilerplate.end())
            ((out += out.empty() ? "" : " ") += "=") += std::string(tag) + "=";
        from = to + 1;
    }
    return out;
}

/**
 * @brief @p text padded with blanks to @p width characters, as str.ljust.
 */
std::string ljust(std::string_view text, std::size_t width) {
    std::string out(text);
    const auto n = co::characters(text);
    if (n < width)
        out.append(width - n, ' ');
    return out;
}

std::string render_table(const std::vector<capture>& captures) {
    if (captures.empty())
        return "(No captures in this bucket yet.)\n";
    struct row {
        std::string link;
        std::string tags;
        std::string description;
    };
    std::vector<row> rows;
    std::size_t title_w = 7;
    std::size_t tags_w = 4;
    std::size_t desc_w = 50;
    for (const auto& c : captures) {
        row r{"[[id:" + c.id + "][" + c.title + "]]",
            display_tags(c.filetags), std::string(co::strip(c.description))};
        title_w = std::max(title_w, co::characters(r.link));
        tags_w = std::max(tags_w, co::characters(r.tags));
        desc_w = std::max(desc_w, co::characters(r.description));
        rows.push_back(std::move(r));
    }
    std::string out = "#+ATTR_HTML: :class hug-leading\n| " +
        ljust("Capture", title_w) + " | " + ljust("Tags", tags_w) + " | " +
        ljust("Description", desc_w) + " |\n|" +
        std::string(title_w + 2, '-') + "+" + std::string(tags_w + 2, '-') +
        "+" + std::string(desc_w + 2, '-') + "|\n";
    for (const auto& r : rows)
        out += "| " + ljust(r.link, title_w) + " | " + ljust(r.tags, tags_w) +
            " | " + ljust(r.description, desc_w) + " |\n";
    return out;
}

void indexes(const ct::corpus_view& v, ct::file_output& out) {
    for (const auto& [bucket, header] : buckets)
        out.files.add(std::string(backlog_root) + std::string(bucket) + ".org",
            std::string(header) + "# BEGIN AUTOGENERATED \xe2\x80\x94 "
            "regenerate_backlog_indexes.py\n" +
            render_table(gather(v, bucket)) + "# END AUTOGENERATED\n");
}

