std::vector<rule_row> rules_of(std::span<const types::descriptor> catalogue) {
    std::vector<const types::descriptor*> codecs;
    bool files = false;
    for (const auto& d : catalogue) {
        if (types::output_of(d) == types::output_kind::files)
            files = true;
        if (!d.rules.empty())
            codecs.push_back(&d);
    }
    std::ranges::stable_sort(codecs, {}, &types::descriptor::name);
    std::vector<rule_row> out;
    for (const auto* d : codecs)
        for (const auto& r : d->rules)
            out.push_back({d->name, &r});
    for (const auto& r : exception_rules)
        out.push_back({exception_codec, &r});
    if (files) {
        out.push_back({every_files_codec, &drift_rule});
        out.push_back({every_files_codec, &names_missing_file_rule});
    }
    return out;
}

std::uint32_t rule_table_version(
    std::span<const types::descriptor> catalogue) {
    auto h = fnv1a(2166136261u, std::to_string(page_format));
    for (const auto& row : rules_of(catalogue)) {
        h = fnv1a(h, row.codec);
        h = fnv1a(h, row.rule->name);
        h = fnv1a(h, row.rule->summary);
        for (const auto source : row.rule->enforces)
            h = fnv1a(h, source);
    }
    return h;
}

std::string rule_table(std::span<const types::descriptor> catalogue,
    const types::corpus_view& documents) {
    const auto rows = rules_of(catalogue);
    std::unordered_set<std::string_view> cited;
    std::size_t citing = 0;
    for (const auto& row : rows) {
        citing += row.rule->enforces.empty() ? 0 : 1;
        cited.insert(row.rule->enforces.begin(), row.rule->enforces.end());
    }

    struct memory {
        std::string_view path;
        std::string_view id;
        std::string_view title;
    };
    std::vector<memory> memories;
    for (std::size_t i = 0; i < documents.size(); ++i) {
        const auto d = documents[i];
        if (keyword(d, "type") == "memory")
            memories.push_back({d.path, id_of(d), keyword(d, "title")});
    }
    std::ranges::sort(memories, {}, &memory::path);
    const auto unenforced = std::ranges::count_if(memories,
        [&](const memory& m) { return !cited.contains(m.id); });

    std::string out(page_head);
    out += std::format("{} rules, {} of which cite a memory or a document "
        "that states them. Of the {} memories of this repository, {} are "
        "cited by no rule.\n\n** Rules\n\n"
        "| Codec | Rule | Statement | Enforces |\n"
        "|-------+------+-----------+----------|\n",
        rows.size(), citing, memories.size(), unenforced);
    for (const auto& row : rows) {
        std::string sources;
        for (const auto id : row.rule->enforces) {
            if (!sources.empty())
                sources += ", ";
            const auto found = documents.find_id(id);
            sources += found ? link(id, keyword(*found, "title"))
                             : std::format("={}=", id);
        }
        out += std::format("| {} | {} | {} | {} |\n",
            row.codec == every_files_codec ? std::string(row.codec)
                                           : std::format("={}=", row.codec),
            cell(row.rule->name), cell(row.rule->summary), cell(sources));
    }

    out += "\n** Unenforced memories\n\n";
    if (unenforced == 0)
        out += "Every memory is cited by some rule.\n";
    for (const auto& m : memories) {
        if (cited.contains(m.id))
            continue;
        out += "- " + (m.id.empty() ? std::format("={}=", m.path)
                                    : link(m.id, m.title)) + "\n";
    }
    return out;
}

