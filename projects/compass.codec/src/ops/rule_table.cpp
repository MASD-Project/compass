/**
 * @brief Bumped when the page would change for the same rows.
 */
constexpr std::uint32_t page_format = 1;

constexpr std::string_view page_head = R"(:PROPERTIES:
:ID: 9DE422EE-3416-4CFD-B15B-4CFD3E77D7F4
:END:
#+title: Rule table
#+description: Every rule compass checks, with its codec, what it enforces and the memories and documents that state it in prose, and the memories no rule enforces.
#+type: knowledge
#+level: cross
#+filetags: :compass:rules:gates:memory:knowledge:
#+created: 2026-11-17
#+updated: 2026-11-17

This page is generated by the =rule_table= codec of compass from the rules
its codecs declare and from the memories of this repository. Edit a codec's
rules or a memory and run =compass generate=, never the page; =compass
check= reports the page as =rule_table/drift= when it disagrees with them.
A rule is named =codec/rule= in a finding and in an inline exception. The
memories no rule cites are the candidates for the next checks.

* Detail

)";

std::string_view keyword(const types::document& d, std::string_view key) {
    const auto k = org::ops::find_keyword(d.tables, key);
    if (k.is_none())
        return {};
    return org::ops::trimmed(d.source, d.tables.keywords.values[k]).of(
        d.source);
}

std::string_view id_of(const types::document& d) {
    const auto p = org::ops::find_document_property(d.tables, "ID");
    if (p.is_none())
        return {};
    return org::ops::trimmed(d.source, d.tables.properties.values[p]).of(
        d.source);
}

std::string cell(std::string_view text) {
    std::string out;
    for (const char c : text) {
        if (c == '|')
            out += "\\vert{}";
        else
            out += c == '\n' ? ' ' : c;
    }
    return out;
}

std::string link(std::string_view id, std::string_view title) {
    return std::format("[[id:{}][{}]]", id, title.empty() ? id : title);
}

std::uint32_t fnv1a(std::uint32_t h, std::string_view s) {
    for (const char c : s) {
        h ^= static_cast<unsigned char>(c);
        h *= 16777619u;
    }
    h ^= 0xffu;
    return h * 16777619u;
}

