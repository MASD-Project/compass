#ifndef COMPASS_MODEL_TYPES_MASD_ENTITY_HPP
#define COMPASS_MODEL_TYPES_MASD_ENTITY_HPP

#include <cstdint>
#include <string>
#include <vector>

namespace compass::model::types {

/**
 * @brief What a key column is to its row. A natural key is a column of the
 * row like any other. The others stay out of the row type: a content hash
 * is the identity of the aggregate the row belongs to, an owner is the key
 * of the row that owns it, an ord is the row's place in its owner's vector,
 * and an identity is generated by the database.
 */
enum class key_kind : std::uint8_t {
    none,
    natural,
    content_hash,
    owner,
    ord,
    identity
};

/**
 * @brief Who writes a column. The row type and the COPY column list carry
 * only what the row writes; the database writes a defaulted or generated
 * column, and the writer's own SQL sets or computes the rest.
 */
enum class written_by : std::uint8_t { row, database, writer };

/**
 * @brief One column of a masd.codegen.entity model, in table order.
 *
 * member is the name of the row's member, the column's name unless the
 * model says otherwise. cpp_type is the type the model states, empty when
 * the context derives it from sql_type. values is the closed list of a
 * text column, which becomes a check and an enumeration named enum_name.
 * generated is the expression of a stored generated column.
 */
struct masd_column {
    std::string name;
    std::string member;
    std::string sql_type;
    std::string cpp_type;
    std::string default_value;
    std::string generated;
    std::string enum_name;
    std::vector<std::string> values;
    bool nullable = false;
    bool primary_key = false;
    bool unique = false;
    key_kind key = key_kind::none;
    written_by writer = written_by::row;
};

/**
 * @brief A single-column foreign key: the column, the table it references,
 * schema-qualified, and whether deleting that row deletes this one.
 */
struct masd_foreign_key {
    std::string column;
    std::string references;
    bool cascade = false;
};

/**
 * @brief An index: its name within the table, its columns, and the access
 * method, operator class and predicate of a partial index, when stated.
 */
struct masd_index {
    std::string name;
    std::vector<std::string> columns;
    bool unique = false;
    std::string method;
    std::string opclass;
    std::string where;
};

/**
 * @brief A table of a masd.codegen.entity model and the row type over it.
 *
 * retained marks a table whose rows exist nowhere else, so a change to it
 * needs a migration that says what becomes of them; its profile sets it.
 * uniques are the table's unique constraints, each a list of columns.
 */
struct masd_entity {
    std::string product;
    std::string component;
    std::string schema;
    std::string entity;
    std::string row_type;
    std::string brief;
    std::string profile;
    bool retained = false;
    std::vector<masd_column> columns;
    std::vector<masd_foreign_key> foreign_keys;
    std::vector<masd_index> indexes;
    std::vector<std::string> checks;
    std::vector<std::vector<std::string>> uniques;
};

/**
 * @brief A masd.codegen.schema model: the schemas of a component's
 * database in the order they are created, and the functions created after
 * every table, each as the SQL that creates it.
 */
struct masd_schema {
    std::string product;
    std::string component;
    std::vector<std::string> schemas;
    std::vector<std::string> functions;
};

/**
 * @brief A masd.codegen.component model: a component of a product, which
 * renders the component-wide files of the facets its physical space table
 * switches on, such as the JSON codec runtime.
 */
struct masd_component {
    std::string product;
    std::string component;
};

/**
 * @brief One field of a message of a masd.codegen.operation model.
 *
 * values is the closed list :values: states: the enumerators of a field
 * whose type is an enumeration, or the texts a string field accepts.
 * encoding is base64 for a string that holds bytes, else empty.
 * http_in is where a route reads the field, path, query or body, empty on a
 * message no route takes; http_name is the query parameter's name when it is
 * not the field's. optional is true when :required: false lets a call leave
 * the field out. description is the field's prose.
 */
struct masd_field {
    std::string name;
    std::string cpp_type;
    std::string default_value;
    std::string encoding;
    std::vector<std::string> values;
    std::string http_in;
    std::string http_name;
    bool optional = false;
    std::string description;
};

/**
 * @brief How HTTP and MCP reach a request message: its route, its place in
 * the catalogue and what the gateway must present. method is empty on a
 * message no route takes.
 */
struct masd_route {
    std::string method;
    std::string path;
    std::string tool;
    std::string area;
    std::string entity;
    bool writes = false;
    bool destructive = false;
    bool idempotent = false;
    std::string summary;
    std::string caller;
    std::string max_body_size;
};

/**
 * @brief One message of a masd.codegen.operation model, in model order,
 * the message it is answered with, when it names one, its prose and its
 * route, when it is a request.
 */
struct masd_message {
    std::string name;
    std::string response;
    std::string description;
    masd_route route;
    std::vector<masd_field> fields;
};

/**
 * @brief A masd.codegen.operation model: the messages of one part of a
 * component's service, the namespace they live in and the headers their
 * fields need.
 */
struct masd_operation {
    std::string component;
    std::string entity;
    std::string ns;
    std::vector<std::string> includes;
    std::vector<masd_message> messages;
};

}

#endif
