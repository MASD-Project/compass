/**
 * @brief The widest braced initialiser the script keeps on one line.
 */
constexpr std::size_t cpp_line = 95;

std::string cpp_quote(std::string_view value) {
    std::string out = "\"";
    for (const char c : value) {
        if (c == '\\' || c == '"')
            out.push_back('\\');
        out.push_back(c);
    }
    return out + "\"";
}

/**
 * @brief cpp_braced: one line while it fits, else one value a line,
 * aligned under the first.
 */
std::string cpp_braced(const std::vector<std::string>& parts) {
    std::string single = "{";
    std::string broken = "{";
    for (std::size_t i = 0; i < parts.size(); ++i) {
        single += (i == 0 ? "" : ", ") + parts[i];
        broken += (i == 0 ? "" : ",\n     ") + parts[i];
    }
    if (single.size() + 1 <= cpp_line)
        return single + "}";
    return broken + "}";
}

std::string cpp_structured(std::initializer_list<std::string_view> values) {
    std::vector<std::string> parts;
    for (const auto v : values)
        parts.push_back(cpp_quote(v));
    return cpp_braced(parts);
}

template <typename Row, typename Render>
std::string cpp_array(std::string_view kind, const std::string& name,
    const std::vector<Row>& rows, Render render_row) {
    const auto head = "constexpr std::array<" + std::string(kind) + ", " +
        std::to_string(rows.size()) + "> " + name;
    if (rows.empty())
        return head + "{};\n";
    std::string lines;
    for (const auto& row : rows)
        lines += "    " + render_row(row) + ",\n";
    return head + "{{\n" + lines + "}};\n";
}

/**
 * @brief cpp_section_tables: the arrays one section's wiring reads, then
 * the section's own row.
 */
std::vector<std::string> cpp_section_tables(std::size_t index,
    const cw::section& s) {
    const auto n = std::to_string(index);
    std::vector<std::string> body{
        cpp_array("curve_entity", "curve_entities_" + n, s.entities,
            [](const cw::entity_vector& e) {
                return cpp_structured({e.entity, e.vector}); }),
        cpp_array("curve_parameter", "curve_parameters_" + n, s.parameters,
            [](const cw::parameter& p) {
                return cpp_structured({p.entity, p.column, p.ore, p.xpath}); }),
        cpp_array("curve_block", "curve_blocks_" + n, s.blocks,
            [](const cw::block& b) {
                return cpp_structured({b.element, b.presence,
                    b.presence_entity}); })};
    std::vector<std::string> collections;
    for (std::size_t position = 0; position < s.collections.size();
         ++position) {
        const auto& c = s.collections[position];
        const auto at = n + "_" + std::to_string(position);
        std::string kind_rows;
        for (std::size_t k = 0; k < c.kinds.size(); ++k) {
            const auto leaves = "curve_leaves_" + at + "_" + std::to_string(k);
            body.push_back(cpp_array("curve_collection_leaf", leaves,
                c.kinds[k].leaves, [](const cw::kind_leaf& l) {
                    return cpp_structured({l.column, l.ore, l.entity,
                        l.vector}); }));
            kind_rows += "    " + cpp_braced({cpp_quote(c.kinds[k].kind),
                leaves}) + ",\n";
        }
        body.push_back("constexpr std::array<curve_collection_kind, " +
            std::to_string(c.kinds.size()) + "> curve_kinds_" + at + "{{\n" +
            kind_rows + "}};\n");
        collections.push_back("    " + cpp_braced({cpp_quote(c.element),
            cpp_quote(c.entity), cpp_quote(c.vector), cpp_quote(c.parent_key),
            cpp_quote(c.kind_column), cpp_quote(c.quote_parent),
            cpp_quote(c.part_parent), "curve_kinds_" + at}));
    }
    std::string rows;
    for (const auto& row : collections)
        rows += row + ",\n";
    body.push_back("constexpr std::array<curve_collection, " +
        std::to_string(collections.size()) + "> curve_collections_" + n +
        (collections.empty() ? "{};\n" : "{{\n" + rows + "}};\n"));
    body.push_back("    " + cpp_braced({cpp_quote(s.name),
        cpp_quote(s.entry_element), cpp_quote("curve_definition_id"),
        "curve_entities_" + n, "curve_parameters_" + n, "curve_blocks_" + n,
        "curve_collections_" + n}));
    return body;
}

/**
 * @brief render_cpp: the gateway's wiring table, before clang-format.
 */
std::string render_cpp(const std::vector<cw::section>& sections) {
    std::string tables;
    std::string rows;
    for (std::size_t i = 0; i < sections.size(); ++i) {
        const auto body = cpp_section_tables(i, sections[i]);
        for (std::size_t j = 0; j + 1 < body.size(); ++j)
            tables += (tables.empty() ? "" : "\n") + body[j];
        rows += body.back() + ",\n";
    }
    return std::string(cpp_licence) +
        "#include \"ores.http/routes/refdata/curve_section_wiring.hpp\"\n"
        "#include <array>\n#include <span>\n#include <string_view>\n\n"
        "namespace ores::http::routes::refdata::wiring {\n\nnamespace {\n\n" +
        tables + "\nconstexpr std::array<curve_section, " +
        std::to_string(sections.size()) + "> curve_section_table{{\n" + rows +
        "}};\n\n}\n\n" + std::string(cpp_footer);
}

/**
 * @brief The entities the guard's value sets are stored in, from the
 * Value set entities table of the check document that names this codec,
 * or why not.
 */
std::expected<vs::storage, std::string> storage_of(const ct::corpus_view& v) {
    constexpr std::string_view codec = "curve_sections_wiring";
    const std::array needs{vs::entities_table};
    const auto data = compass::codec::ops::tables_for(codec,
        v.option(compass::codec::ops::data_option), needs);
    if (!data)
        return std::unexpected(data.error());
    return vs::read_storage(v, *data, codec).transform_error(
        [](const vs::unreadable& u) { return u.message; });
}

void run(const ct::corpus_view& v, ct::file_output& out) {
    const auto refuse = [&](const std::string& why) {
        co::refuse(out, module_path, why, "Correct the curve configuration "
            "projection or the ORE schema the reason names.");
    };
    const auto projection = v.read_file(cw::projection_path);
    const auto schema = v.read_file(cw::schema_path);
    if (!projection || !schema) {
        refuse("cannot read " + std::string(!projection ? cw::projection_path
            : cw::schema_path));
        return;
    }
    const auto declared = cw::leaves_of_schema(*schema);
    if (!declared) {
        refuse("the schema " + std::string(cw::schema_path) + " names a "
            "type it does not declare");
        return;
    }
    const auto wired = cw::wiring(*projection, *declared);
    if (!wired) {
        refuse("a section table of " + std::string(cw::projection_path) +
            " cannot be read");
        return;
    }
    if (!wired->problems.empty()) {
        refuse(co::listed(wired->problems));
        return;
    }
    const auto kinds = cw::kind_leaves(*projection).first;
    const auto [default_types, problems] =
        cw::default_curve_types(*projection);
    if (!problems.empty()) {
        refuse(co::listed(problems));
        return;
    }
    out.files.add(module_path, render(wired->sections));
    out.files.add(sql_path, render_sql(kinds, default_types));
    out.files.add(cpp_header_path, std::string(cpp_licence) +
        std::string(cpp_header));
    out.files.add(cpp_source_path, render_cpp(wired->sections));
    const auto columns = ops::curve_columns(v, wired->sections);
    if (!columns) {
        co::refuse(out, map_path, "the curve configuration columns cannot be "
            "derived: a curve entity has no model with its :tablename:, or "
            "two entities share a table", "Give every curve entity a model "
            "with its own :tablename:.");
        return;
    }
    std::map<std::string, std::string> tables;
    for (const auto& c : *columns)
        tables.insert_or_assign(c.table, c.entity);
    out.files.add(map_path, render_map(*columns));
    out.files.add(drop_path, render_drop(tables));
    const auto names = storage_of(v);
    if (!names) {
        co::refuse(out, guard_path, names.error(), "Name each role's entity "
            "in the check document's Value set entities table, and give that "
            "entity one model under a modeling/ directory.");
        return;
    }
    out.files.add(guard_path, render_guard(tables, *names));
}

