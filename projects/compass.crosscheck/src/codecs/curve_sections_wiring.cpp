constexpr std::string_view sql_functions = R"SQL(
/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 *
 * Generated by projects/ores.sql/utility/generate_curve_section_parameters.py
 * from the curve configuration projection. To modify, change the projection's
 * import_segments or parts_of_default_curve_type and run the generator.
 *
 * A curve segment's settings are parts of the segment, and each segment
 * element has only some of them; a default curve configuration's settings are
 * parts of the configuration, and each type has only some of them. The
 * projection's import_segments and parts_of_default_curve_type are the one
 * statement of which construction fills which part, so these functions are
 * written from them. Each part's insert trigger calls its function on the row
 * the part names.
 */

create or replace function ores_refdata_validate_curve_segment_part_fn(
    p_tenant_id uuid,
    p_segment_id uuid,
    p_part text,
    p_kinds text[]
) returns uuid as $$
declare
    v_kind text;
begin
    select t.segment_kind into v_kind
    from ores_refdata_curve_segments_tbl s
    join ores_refdata_curve_segment_types_tbl t
      on t.tenant_id = s.tenant_id
     and t.code = s.segment_type
     and t.valid_to = ores_utility_infinity_timestamp_fn()
    where s.tenant_id = p_tenant_id
      and s.id = p_segment_id
      and s.valid_to = ores_utility_infinity_timestamp_fn();

    -- The trigger's key check refuses a segment that is not there.
    if v_kind is not null and not (v_kind = any(p_kinds)) then
        raise exception 'Invalid curve_segment_id: %. A % segment has no % part.',
            p_segment_id, v_kind, p_part
            using errcode = '23514';
    end if;
    return p_segment_id;
end;
$$ language plpgsql stable;

create or replace function ores_refdata_validate_default_curve_part_fn(
    p_tenant_id uuid,
    p_configuration_id uuid,
    p_part text,
    p_types text[]
) returns uuid as $$
declare
    v_type text;
begin
    select c.default_curve_type into v_type
    from ores_refdata_default_curve_configurations_tbl c
    where c.tenant_id = p_tenant_id
      and c.id = p_configuration_id
      and c.valid_to = ores_utility_infinity_timestamp_fn();

    -- The trigger's key check refuses a configuration that is not there.
    if v_type is not null and not (v_type = any(p_types)) then
        raise exception 'Invalid default_curve_configuration_id: %. A % default curve has no % part.',
            p_configuration_id, v_type, p_part
            using errcode = '23514';
    end if;
    return p_configuration_id;
end;
$$ language plpgsql stable;
)SQL";

std::string quote(std::string_view value) {
    std::string out = "'";
    for (const char c : value) {
        if (c == '\\' || c == '\'')
            out.push_back('\\');
        out.push_back(c);
    }
    return out + "'";
}

std::string field(std::size_t indent, std::string_view key,
    std::string_view value) {
    return std::string(indent, ' ') + std::string(key) + ": " + quote(value) +
        ",\n";
}

template <typename Row, typename Render>
std::string joined(const std::vector<Row>& rows, Render render_one) {
    std::string out;
    for (const auto& row : rows) {
        if (!out.empty())
            out.push_back('\n');
        out += render_one(row);
    }
    return out;
}

template <typename Row, typename Render>
std::string render_list(std::string_view name, const std::vector<Row>& rows,
    Render render_one) {
    if (rows.empty())
        return "        " + std::string(name) + ": [],\n";
    return "        " + std::string(name) + ": [\n" + joined(rows, render_one) +
        "\n        ],\n";
}

std::string render_kind(const cw::segment_kind& k) {
    return "                    {\n" + field(24, "kind", k.kind) +
        "                        leaves: [\n" +
        joined(k.leaves, [](const cw::kind_leaf& l) {
            return "                            {\n" +
                field(32, "column", l.column) + field(32, "ore", l.ore) +
                field(32, "entity", l.entity) + field(32, "vector", l.vector) +
                "                            },";
        }) +
        "\n                        ],\n                    },";
}

std::string render(const std::vector<cw::section>& sections) {
    std::string out(licence);
    out += header;
    out += joined(sections, [](const cw::section& s) {
        return "    {\n" + field(8, "section", s.name) +
            field(8, "entryElement", s.entry_element) +
            field(8, "definitionKey", "curve_definition_id") +
            render_list("entities", s.entities, [](const cw::entity_vector& e) {
                return "            {\n" + field(16, "entity", e.entity) +
                    field(16, "vector", e.vector) + "            },";
            }) +
            render_list("parameters", s.parameters, [](const cw::parameter& p) {
                return "            {\n" + field(16, "entity", p.entity) +
                    field(16, "column", p.column) + field(16, "ore", p.ore) +
                    field(16, "xpath", p.xpath) + "            },";
            }) +
            render_list("blocks", s.blocks, [](const cw::block& b) {
                return "            {\n" + field(16, "element", b.element) +
                    field(16, "presence", b.presence) +
                    field(16, "presenceEntity", b.presence_entity) +
                    "            },";
            }) +
            render_list("collections", s.collections,
                [](const cw::collection& c) {
                    return "            {\n" + field(16, "element", c.element) +
                        field(16, "entity", c.entity) +
                        field(16, "vector", c.vector) +
                        field(16, "parentKey", c.parent_key) +
                        field(16, "kindColumn", c.kind_column) +
                        field(16, "quoteParent", c.quote_parent) +
                        field(16, "partParent", c.part_parent) +
                        "                kinds: [\n" +
                        joined(c.kinds, render_kind) +
                        "\n                ],\n            },";
                }) +
            "    },";
    });
    out += footer;
    return out;
}

std::string quoted_list(const std::vector<std::string>& items) {
    std::string out;
    for (const auto& i : items) {
        if (!out.empty())
            out += ", ";
        out += "'" + i + "'";
    }
    return cw::fill(out, 80, "            ");
}

std::string part_function(std::string_view part, std::string_view owner,
    const std::vector<std::string>& owners) {
    return "\ncreate or replace function ores_refdata_validate_" +
        std::string(part) + "_fn(\n    p_tenant_id uuid,\n    p_value uuid\n"
        ") returns uuid as $$\n    select ores_refdata_validate_" +
        std::string(owner) + "_part_fn(\n        p_tenant_id, p_value, '" +
        std::string(part) + "',\n        array[\n" + quoted_list(owners) +
        "\n        ]);\n$$ language sql stable;\n";
}

std::string render_sql(const std::vector<cw::segment_kind>& kinds,
    const cw::types_by_part& default_types) {
    std::string out(sql_licence);
    out += sql_functions;
    for (const auto& [part, types] : default_types)
        out += part_function(part, "default_curve", types);
    cw::types_by_part kinds_by_part;
    for (const auto& k : kinds)
        for (const auto& part : k.parts) {
            auto it = std::ranges::find_if(kinds_by_part,
                [&](const auto& e) { return e.first == part; });
            if (it == kinds_by_part.end()) {
                kinds_by_part.emplace_back(part, std::vector<std::string>{});
                it = std::prev(kinds_by_part.end());
            }
            if (std::ranges::find(it->second, k.kind) == it->second.end())
                it->second.push_back(k.kind);
        }
    for (const auto& [part, owners] : kinds_by_part)
        out += part_function(part, "curve_segment", owners);
    return out;
}

void run(const ct::corpus_view& v, ct::file_table& out) {
    const auto projection = v.read_file(cw::projection_path);
    const auto schema = v.read_file(cw::schema_path);
    if (!projection || !schema)
        return;
    const auto declared = cw::leaves_of_schema(*schema);
    if (!declared)
        return;
    const auto wired = cw::wiring(*projection, *declared);
    if (!wired || !wired->problems.empty())
        return;
    const auto kinds = cw::kind_leaves(*projection).first;
    const auto [default_types, problems] =
        cw::default_curve_types(*projection);
    if (!problems.empty())
        return;
    out.add(module_path, render(wired->sections));
    out.add(sql_path, render_sql(kinds, default_types));
}

