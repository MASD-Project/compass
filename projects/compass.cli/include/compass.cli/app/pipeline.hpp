#ifndef COMPASS_CLI_APP_PIPELINE_HPP
#define COMPASS_CLI_APP_PIPELINE_HPP

#include <string_view>
#include "compass.cli/types/options.hpp"
#include "compass.cli/types/results.hpp"

/**
 * The commands of the compass executable, one function each. Every
 * command but gc first runs the steps of app/steps.hpp: list the org files
 * of the checkout, build the type registry from the contract pages under
 * the meta directory, resolve their IDs, load each object from the store
 * or parse the file, and run the enabled codecs from the dependency record
 * of the checkout and the result cache of the repository. The store is
 * compass/objects under the git common directory. None of these functions
 * prints.
 */
namespace compass::cli::app {

/**
 * @brief Runs the pipeline and makes the files under the output root hold
 * what the codecs emit, touching only the files that differ.
 *
 * Stores the parsed objects, the worktree index, the result cache and the
 * dependency record, then the outputs and the written-outputs record.
 * Outputs are written only when every file loaded and the registry has no
 * problem.
 *
 * @throws std::system_error or std::filesystem::filesystem_error when the
 * checkout, the meta directory or the output root cannot be read or
 * written.
 */
[[nodiscard]] types::generate_result generate(const types::options& o);

/**
 * @brief Runs the pipeline and diffs what generate would write against
 * the files under the output root. Writes nothing anywhere.
 *
 * @throws as generate does.
 */
[[nodiscard]] types::diff_result diff(const types::options& o);

/**
 * @brief Runs the pipeline and returns the diagnostics of every codec.
 *
 * Stores the parsed objects, the worktree index, the result cache and the
 * dependency record, so the next command starts warm, and writes no
 * output.
 *
 * When @p o names a commit, these are the diagnostics at that commit: its
 * files are read from git's object database, with no checkout, and each
 * output is compared with the commit's file at its path, as a check of a
 * fresh checkout of the commit would. An org document whose blob the
 * store has parsed is not parsed again, and a file that is not a document
 * is read only when a codec that runs reads it. Only the parsed objects
 * and the result cache, which every worktree shares, are stored; the
 * worktree index and dependency record of the checkout are left alone.
 *
 * @throws as generate does, and std::runtime_error when the commit or a
 * tree of it cannot be read, or the meta directory or the output root is
 * not under the checkout.
 */
[[nodiscard]] types::check_result check(const types::options& o);

/**
 * @brief Checks one edited file of the checkout of @p o, as an edit hook
 * does, and returns the findings on it and those the edit caused.
 *
 * @p path is relative to the checkout, and @p created says the edit may
 * have created it. The units of the dependency record an edit to it may
 * change are found through the record's unit index and their heads read
 * alone, with no other unit and no output loaded or hashed: those that
 * read it, produced it or report on it, those that list a pattern it
 * matches when it is new and, for a document, every document unit of it
 * and every unit that enumerates documents or looks up an ID it holds.
 * The documents are loaded only when one of those codecs may read them. Only those units run, through
 * the record and the result cache as check runs them. The findings are
 * every finding on @p path, the findings of those units on other files
 * that their recorded findings lack, and the drift of @p path and of each
 * output whose generated bytes changed. Valid inline exceptions excuse
 * them as check excuses them; the exception findings are those of
 * @p path.
 *
 * Nothing runs when no unit names @p path and it is no document, or the
 * checkout does not list it. Nothing is written: not the store, the
 * record or the result cache. A note says why the file could not be
 * checked when the record is missing, unreadable or replaced while read,
 * the registry has a problem, or @p path is the configuration file or a
 * contract page, which change what every unit sees.
 *
 * The record is taken to describe the checkout as it was before the edit:
 * a finding another edit since the last check caused on another file may
 * be reported as caused by this one.
 *
 * @throws as check does.
 */
[[nodiscard]] types::hook_result hook(const types::options& o,
    const std::string& path, bool created);

/**
 * @brief Checks the checkout and the merge base of HEAD and @p base, and
 * splits the findings of the checkout into those the merge base did not
 * have and those it did.
 *
 * @p base is any revision; when empty, the upstream of the current
 * branch, else origin/main. git rev-parse resolves HEAD and the base, one
 * git merge-base finds the merge base, and git diff -M runs only when a
 * file with findings at the merge base is gone from HEAD and no file of
 * HEAD holds its blob. Both
 * checks run with the configuration of @p o, so a rule that is new in
 * the checkout's configuration excuses what the merge base already broke.
 * The checkout is checked as check does, uncommitted changes included,
 * and renames are followed from the merge base to HEAD. See
 * ops::split_new for the matching.
 *
 * @throws as check does, and std::runtime_error when @p base names no
 * commit, there is no default base, or HEAD and the base share no
 * history.
 */
[[nodiscard]] types::ratchet_result ratchet(const types::options& o,
    std::string_view base);

/**
 * @brief Collects the store with the collection options of @p o.
 *
 * @throws std::runtime_error when the checkout is not a git checkout or
 * an index cannot be read, before anything is removed.
 */
[[nodiscard]] types::gc_result gc(const types::options& o);

}

#endif
